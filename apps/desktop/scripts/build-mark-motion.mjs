#!/usr/bin/env node
// Builds the Bubble AI mark's motion for the desktop setup page from the web app's source, so both
// move the same way: apps/web/src/components/markStandalone.ts → src/mark-motion.js (window.BubbleMark),
// and mark.css → src/mark.css. The setup page runs before the app, without React, so it gets plain script.
//
//   node apps/desktop/scripts/build-mark-motion.mjs          writes the two files
//   node apps/desktop/scripts/build-mark-motion.mjs --check  fails if they are out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const desktop = fileURLToPath(new URL("..", import.meta.url));
const web = path.resolve(desktop, "../web/src/components");
const banner = "/* Generated by apps/desktop/scripts/build-mark-motion.mjs from apps/web/src/components. Do not edit. */";

export async function markFiles() {
  const out = await build({
    entryPoints: [path.join(web, "markStandalone.ts")],
    bundle: true,
    write: false,
    format: "iife",
    globalName: "BubbleMark",
    target: "chrome120",
    legalComments: "none",
    banner: { js: banner },
    plugins: [{
      // the app's theme store needs React; here reduced motion is just the system setting
      name: "theme-shim",
      setup(b) {
        b.onResolve({ filter: /\/theme\.ts$/ }, () => ({ path: "theme", namespace: "shim" }));
        b.onLoad({ filter: /.*/, namespace: "shim" }, () => ({ contents: 'export const motionReduced = () => matchMedia("(prefers-reduced-motion: reduce)").matches;', loader: "ts" }));
      },
    }],
  });
  return {
    "mark-motion.js": out.outputFiles[0].text,
    "mark.css": `${banner}\n${fs.readFileSync(path.join(web, "mark.css"), "utf8")}`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await markFiles();
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [name, text] of Object.entries(files)) {
    const dest = path.join(desktop, "src", name);
    if (check) stale ||= !fs.existsSync(dest) || fs.readFileSync(dest, "utf8") !== text;
    else fs.writeFileSync(dest, text);
  }
  if (stale) {
    console.error("apps/desktop/src/mark-motion.js or mark.css is out of date: run node apps/desktop/scripts/build-mark-motion.mjs");
    process.exit(1);
  }
}
